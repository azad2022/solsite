export type ReferralTranslationKey = keyof typeof messages['fa-IR'];
export function referralT(locale: PayLocale, key: ReferralTranslationKey): string { return messages[locale][key]; }

export function referralActiveT(locale: PayLocale, active: boolean): string {
  return active ? messages[locale].active : messages[locale].inactive;
}

export function referralCommissionStatusT(locale: PayLocale, commission: PayCommission): string {
  switch (commission.status) {
    case 'pending': return messages[locale].commissionPending;
    case 'approved': return messages[locale].commissionApproved;
    case 'paid': return messages[locale].commissionPaid;
    case 'void': return messages[locale].commissionVoid;
  }
}

export function referralAffiliateStatusT(locale: PayLocale, status: string): string {
  switch (status) {
    case 'active': return messages[locale].affiliateActive;
    case 'pending': return messages[locale].affiliatePending;
    case 'suspended': return messages[locale].affiliateSuspended;
    case 'closed': return messages[locale].affiliateClosed;
    default: return status;
  }
}
