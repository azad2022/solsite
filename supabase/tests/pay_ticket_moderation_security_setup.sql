-- Minimal isolated schema fixture for executing the real ticket moderation migration in CI.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN EXECUTE 'CREATE ROLE anon NOLOGIN'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN EXECUTE 'CREATE ROLE authenticated NOLOGIN'; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN EXECUTE 'CREATE ROLE service_role NOLOGIN BYPASSRLS'; END IF;
END;
$$;

GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

CREATE TABLE public.users (
  id text PRIMARY KEY,
  role text NOT NULL DEFAULT 'user',
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.pay_merchants (
  id uuid PRIMARY KEY,
  status text NOT NULL DEFAULT 'active'
);

CREATE TABLE public.pay_merchant_members (
  merchant_id uuid NOT NULL REFERENCES public.pay_merchants(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'active',
  PRIMARY KEY (merchant_id, user_id)
);

CREATE TABLE public.pay_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  merchant_id uuid NOT NULL REFERENCES public.pay_merchants(id) ON DELETE CASCADE,
  created_by_user_id text NOT NULL REFERENCES public.users(id),
  subject text NOT NULL,
  status text NOT NULL DEFAULT 'open',
  priority text NOT NULL DEFAULT 'normal',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz NULL,
  CONSTRAINT pay_tickets_subject_len CHECK (char_length(trim(subject)) BETWEEN 3 AND 160),
  CONSTRAINT pay_tickets_status_check CHECK (status IN ('open','pending_customer','pending_admin','resolved','closed')),
  CONSTRAINT pay_tickets_priority_check CHECK (priority IN ('normal','high','urgent'))
);

CREATE TABLE public.pay_ticket_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES public.pay_tickets(id) ON DELETE CASCADE,
  author_user_id text NOT NULL REFERENCES public.users(id),
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pay_ticket_messages_body_len CHECK (char_length(trim(body)) BETWEEN 1 AND 10000)
);

CREATE TABLE public.pay_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id uuid NULL REFERENCES public.pay_merchants(id),
  actor_user_id text NOT NULL REFERENCES public.users(id),
  event_type text NOT NULL,
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.pay_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pay_ticket_messages ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.pay_tickets, public.pay_ticket_messages TO authenticated;

CREATE OR REPLACE FUNCTION public.pay_request_user_id()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '');
$$;

CREATE OR REPLACE FUNCTION public.pay_is_site_admin(p_user_id text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.id = p_user_id AND u.is_active = true AND u.role = 'admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.pay_is_site_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT public.pay_is_site_admin(public.pay_request_user_id());
$$;

CREATE OR REPLACE FUNCTION public.pay_has_merchant_access(p_merchant_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.pay_merchant_members m
    WHERE m.merchant_id = p_merchant_id
      AND m.user_id = public.pay_request_user_id()
      AND m.status = 'active'
  );
$$;

GRANT EXECUTE ON FUNCTION public.pay_request_user_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.pay_is_site_admin(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.pay_is_site_admin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.pay_has_merchant_access(uuid) TO authenticated;
